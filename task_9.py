units = {
    "м": ("длина", 1),
    "км": ("длина", 1000),
    "см": ("длина", 0.01),
    "мм": ("длина", 0.001),
    "кг": ("масса", 1),
    "г": ("масса", 0.001),
    "т": ("масса", 1000),
    "фунт": ("масса", 0.453592),
    "с": ("время", 1),
    "мин": ("время", 60),
    "ч": ("время", 3600),
    "сутки": ("время", 86400)
}
print("Доступные единицы:", ", ".join(units))
iz = input("Из какой единицы переводим? ")
v = input("В какую единицу переводим? ")
value = float(input("Введите значение: "))
if iz in units and v in units:
    if units[iz][0] == units[v][0]:
        result = value * units[iz][1] / units[v][1]
        print("Результат:", result, v)
    else:
        print("Нельзя переводить разные типы величин")
else:
    print("Нет такой единицы измерения")